const fs = require('fs');
const assert = require('assert');
const vm = require('vm');

const app = fs.readFileSync('js/app-v2.js','utf8');
const styles = fs.readFileSync('css/styles.css','utf8');
const html = fs.readFileSync('index.html','utf8');
const worker = fs.readFileSync('sw.js','utf8');

assert(app.includes('id="drivePdfUrl"'), 'Google Drive link field is missing');
assert(app.includes('id="drivePdfImport"'), 'Google Drive import button is missing');
assert(app.includes('for="storyFileInput">☁️ CHOOSE FROM GOOGLE DRIVE'), 'Native Google Drive file-picker button is missing');
assert(app.includes('Choose <b>Drive</b> and open your book folder'), 'Android Drive folder instructions are missing');
assert(app.includes('select up to 24 page images together'), 'Drive folder page selection instructions are missing');
assert(app.includes('Drive folder links cannot be pasted here'), 'Direct-link and folder-picker paths are not clearly separated');
assert(app.includes('function googleDrivePdfReference(value)'), 'Google Drive file reference parser is missing');
assert(app.includes("url.pathname.match(/\\/d\\/([^/]+)/i)"), 'Standard and mobile Drive file links are not recognized');
assert(app.includes("url.searchParams.get('id')"), 'Drive download-style links are not recognized');
assert(app.includes("if(/\\/folders?\\//i.test(url.pathname))"), 'Drive folder links do not receive a clear file-link instruction');
assert(app.includes("raw.match(/https?:\\/\\/[^\\s]+/i)"), 'Drive links copied with surrounding text are not normalized');
assert(app.includes("if(/^[a-z0-9_-]{10,}$/i.test(candidate))return {id:candidate,resourceKey:''}"), 'A pasted Drive file ID is not accepted');
assert(app.includes("url.searchParams.get('resourcekey')||url.searchParams.get('resourceKey')"), 'Drive sharing resource keys are discarded');
assert(app.includes("if(reference.resourceKey)url.searchParams.set('resourcekey',reference.resourceKey)"), 'Drive resource keys are missing from downloads');
assert(app.includes("['https://drive.usercontent.google.com/download','https://drive.google.com/uc']"), 'Alternate Drive download routes are missing');
assert(app.includes("fetch(downloadUrl,{mode:'cors',credentials:'omit',redirect:'follow',cache:'no-store'})"), 'Drive PDF download is not mobile-safe');
assert(app.includes('for(const [index,downloadUrl] of googleDriveDownloadUrls(reference).entries())'), 'Drive download does not retry its alternate route');
assert(app.includes("signature.startsWith('%PDF')"), 'Non-PDF Drive responses are not rejected');
assert(app.includes("blob.size>30*1024*1024"), 'Drive PDFs do not use the upload size safety limit');
assert(app.includes("PdfStoryReader.extract(file"), 'Drive PDFs do not use the locked PDF reader');
assert(app.includes("MovieStudio.importPages(result.pages"), 'Drive PDF pages are not turned into movie scenes');
assert(app.includes("source:'google-drive'"), 'Drive imports are not identified in movie source data');
assert(app.includes("classList.add('file-import-active')"), 'App updates can interrupt an active Drive import');
assert(app.includes("'storyspark-import-finished'"), 'Deferred app refresh is not resumed after a Drive import');
assert(styles.includes('@media(max-width:520px){.drive-link-row{grid-template-columns:1fr}'), 'Drive link controls do not stack on narrow phones');
assert(styles.includes('.drive-native-card>.btn{display:block;width:100%'), 'Native Drive picker is not phone friendly');
assert(html.includes('css/styles.css?v=5.6'), 'Drive link mobile styling is not cache-busted');
assert(html.includes('js/app-v2.js?v=5.12'), 'Drive link controller is not cache-busted');
assert(worker.includes("const CACHE='story-spark-mobile-v22'"), 'Installed phones will not receive Drive link imports');

const parserStart=app.indexOf('function googleDrivePdfReference(value)');
const parserEnd=app.indexOf('\nfunction googleDriveDownloadUrl',parserStart);
const parseDriveReference=vm.runInNewContext(`(${app.slice(parserStart,parserEnd)})`,{URL});
const urlStart=app.indexOf('function googleDriveDownloadUrls(reference)');
const urlEnd=app.indexOf('\nasync function fetchGoogleDrivePdf',urlStart);
const makeDriveUrls=vm.runInNewContext(`(${app.slice(urlStart,urlEnd)})`,{URL});
const sampleId='18cpd_3kqi6SPsIVMKklmd3EGgE_sDFFC';
assert.equal(parseDriveReference(`https://drive.google.com/file/d/${sampleId}/view?usp=sharing`).id,sampleId,'Standard Drive file link failed');
assert.equal(parseDriveReference(`https://drive.google.com/file/u/0/d/${sampleId}/view?usp=drivesdk`).id,sampleId,'Mobile/account Drive file link failed');
assert.equal(parseDriveReference(`https://drive.google.com/open?id=${sampleId}`).id,sampleId,'Query-style Drive file link failed');
assert.equal(parseDriveReference(`Here is my book: https://drive.google.com/file/d/${sampleId}/view`).id,sampleId,'Drive link copied with text failed');
assert.equal(parseDriveReference(sampleId).id,sampleId,'Bare Drive file ID failed');
assert.throws(()=>parseDriveReference(`https://drive.google.com/drive/folders/${sampleId}`),/folder link/i,'Folder link did not receive a clear error');
const keyed=parseDriveReference(`https://drive.google.com/file/d/${sampleId}/view?resourcekey=0-secretKey&usp=sharing`);
assert.equal(keyed.resourceKey,'0-secretKey','Drive resource key was not preserved');
const downloadUrls=makeDriveUrls(keyed);
assert.equal(downloadUrls.length,2,'Drive download does not have two routes');
assert(downloadUrls.some(url=>new URL(url).hostname==='drive.usercontent.google.com'),'Primary Drive route is missing');
assert(downloadUrls.some(url=>new URL(url).hostname==='drive.google.com'),'Alternate Drive route is missing');
assert(downloadUrls.every(url=>new URL(url).searchParams.get('resourcekey')==='0-secretKey'),'Drive resource key was not sent to every route');

console.log('Google Drive PDF smoke passed: public link parsing, safe download, PDF validation, movie conversion, mobile layout, and offline updates are connected.');
